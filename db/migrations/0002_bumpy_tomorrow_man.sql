CREATE TABLE `partners` (
	`id` serial AUTO_INCREMENT NOT NULL,
	`slug` varchar(191) NOT NULL,
	`name` varchar(191) NOT NULL,
	`tagline` varchar(255) NOT NULL DEFAULT '',
	`excerpt` text NOT NULL,
	`location` varchar(191) NOT NULL DEFAULT '',
	`hero_image` varchar(512) NOT NULL DEFAULT '',
	`hero_alt` varchar(255) NOT NULL DEFAULT '',
	`card_image` varchar(512) NOT NULL DEFAULT '',
	`card_alt` varchar(255) NOT NULL DEFAULT '',
	`meta_title` varchar(255) NOT NULL DEFAULT '',
	`meta_description` varchar(512) NOT NULL DEFAULT '',
	`territory_plan` varchar(512) NOT NULL DEFAULT '',
	`territory_plan_alt` varchar(255) NOT NULL DEFAULT '',
	`video_url` varchar(1024),
	`content` json NOT NULL,
	`sort_order` int NOT NULL DEFAULT 0,
	`is_published` boolean NOT NULL DEFAULT true,
	`created_at` timestamp NOT NULL DEFAULT (now()),
	`updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `partners_id` PRIMARY KEY(`id`),
	CONSTRAINT `partners_slug_unique` UNIQUE(`slug`)
);
